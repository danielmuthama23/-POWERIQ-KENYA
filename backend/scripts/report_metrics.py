"""Regenerates docs/METRICS.md from the real held-out evaluation. Run: python -m scripts.report_metrics"""
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")
from app.service import PowerIQ

def f(v, d=2):
    return "n/a" if v is None else f"{v:.{d}f}"

svc = PowerIQ()
m = svc.metrics_summary()
L = ["# POWERIQ measured model performance", "",
     f"Generated by `scripts/report_metrics.py` at {m['trained_at']} (seed {svc.seed}). {m['evaluation_note']}", "",
     "## Demand forecasting (national total, last 28 days held out)", "",
     "| Horizon | MAE MW | RMSE MW | MAPE % | Baseline MAPE % (same hour last week) | Baseline MAPE % (last available day) | 80% interval coverage |", "|---|---|---|---|---|---|---|"]
for h in (1, 6, 24, 72):
    d = m["demand"][f"h{h}"]; n = d["national"]
    L.append(f"| {h} h | {f(n['model']['mae'],1)} | {f(n['model']['rmse'],1)} | {f(n['model']['mape_pct'])} | {f(n['baseline_same_hour_last_week']['mape_pct'])} | {f(n['baseline_same_hour_last_available_day']['mape_pct'])} | {f(d['interval_80_empirical_coverage'])} |")
L += ["", "## Generation forecasting (by source, last 28 days held out)", "",
      "MAPE only where actual output > 5% of installed capacity.", "",
      "| Source | Horizon | Model MAE | Model RMSE | Model MAPE % | Persistence MAE | Last-day MAE | Beats best baseline (MAE) | Beats best baseline (RMSE) |", "|---|---|---|---|---|---|---|---|---|"]
for v in m["generation"].values():
    L.append(f"| {v['source']} | {v['horizon_h']} h | {f(v['model']['mae'],1)} | {f(v['model']['rmse'],1)} | {f(v['model']['mape_pct'],1)} | {f(v['baseline_persistence']['mae'],1)} | {f(v['baseline_same_hour_last_available_day']['mae'],1)} | {v['beats_best_baseline_mae']} | {v['beats_best_baseline_rmse']} |")
def cls(name, x):
    c = x["confusion_matrix"]
    return f"| {name} | {f(x['precision'])} | {f(x['recall'])} | {f(x['f1'])} | {f(x.get('roc_auc'))} | TP {c['tp']} / FP {c['fp']} / FN {c['fn']} / TN {c['tn']} |"
hdr = ["| Method | Precision | Recall | F1 | ROC AUC | Confusion matrix |", "|---|---|---|---|---|---|"]
mt, an, ls = m["maintenance"], m["anomaly"], m["loss"]
L += ["", f"## Predictive maintenance (label: fault within 14 days; test prevalence {f(mt['test_prevalence'])})", ""] + hdr + [cls("XGBoost", mt["model"]), cls("Vibration p90 threshold baseline", mt["baseline_vibration_threshold_p90"]), cls("Always negative", mt["baseline_always_negative"])]
L += ["", f"## Anomaly detection (hourly telemetry; test anomaly rate {f(an['test_anomaly_rate'],3)})", ""] + hdr + [cls("Isolation Forest", an["isolation_forest"]), cls("Z-score 3.5 baseline", an["baseline_zscore_3.5"])]
L += ["", f"## Electricity loss detection (months 9-11; positive rate {f(ls['test_positive_rate'],3)})", ""] + hdr + [cls("Isolation Forest", ls["isolation_forest"]), cls("Hybrid (IF and NTL>=4%)", ls["hybrid_iforest_and_ntl_ge_4pct"]), cls("NTL>=5% rule baseline", ls["baseline_ntl_est_ge_5pct"])]
L += ["", "**Caveat:** losses are injected with large effect sizes, so the simple rule separates the classes perfectly; real feeders will be harder."]
Path(__file__).resolve().parents[2].joinpath("docs/METRICS.md").write_text("\n".join(L) + "\n")
print("written")
